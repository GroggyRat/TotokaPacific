// Generates the globe's land dots and the static (no-WebGL / reduced-motion)
// SVG fallback from Natural Earth 110m land. Run: node scripts/build-globe.mjs
import fs from "node:fs";
import { createRequire } from "node:module";
import { feature } from "topojson-client";
import { geoContains, geoOrthographic, geoPath, geoGraticule10, geoInterpolate } from "d3-geo";

const require = createRequire(import.meta.url);
const topo = require("world-atlas/land-110m.json");
const land = feature(topo, topo.objects.land);
const { ORIGIN, DESTINATIONS } = await import("./globe-points.mjs");

// Fibonacci sphere, keep points on land.
const N = 70000;
const golden = Math.PI * (3 - Math.sqrt(5));
const pts = [];
for (let i = 0; i < N; i++) {
  const y = 1 - (i / (N - 1)) * 2;
  const lat = (Math.asin(y) * 180) / Math.PI;
  let lon = ((golden * i * 180) / Math.PI) % 360;
  if (lon > 180) lon -= 360;
  if (geoContains(land, [lon, lat])) pts.push(Math.round(lat * 100), Math.round(lon * 100));
}
const buf = Buffer.from(new Int16Array(pts).buffer);
fs.writeFileSync("public/data/land-dots.bin", buf);
console.log("land dots:", pts.length / 2, (buf.length / 1024).toFixed(1) + "KB");

// Static fallback: orthographic view centred on Fiji.
const proj = geoOrthographic().rotate([-ORIGIN.lon, -ORIGIN.lat + 8]).scale(240).translate([250, 250]).clipAngle(90).precision(0.3);
const path = geoPath(proj);
const round = (d) => d.replace(/(\d+)\.\d+/g, "$1");
const arcs = DESTINATIONS.map((d) => {
  const ip = geoInterpolate([ORIGIN.lon, ORIGIN.lat], [d.lon, d.lat]);
  const coords = Array.from({ length: 33 }, (_, i) => ip(i / 32));
  return round(path({ type: "LineString", coordinates: coords }) || "");
});
const origin = proj([ORIGIN.lon, ORIGIN.lat]).map((n) => +n.toFixed(1));
const out = `// Generated by scripts/build-globe.mjs. Do not edit.
export const globeStatic = ${JSON.stringify({
  land: round(path(land)),
  graticule: round(path(geoGraticule10())),
  arcs,
  origin,
})};
`;
fs.writeFileSync("lib/globeStatic.ts", out);
console.log("static svg:", (out.length / 1024).toFixed(1) + "KB");
